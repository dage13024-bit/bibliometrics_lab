bibfile.plot_bars(view="notebook", statistic="dpy", topn=20)

print("\n▶ 年度被引频次（Citations per Year）")
bibfile.plot_bars(view="notebook", statistic="cpy", topn=20)

print("\n▶ 布拉德福核心期刊区（Bradford Zone 1）")
